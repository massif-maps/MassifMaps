#!/usr/bin/env node
//
// Generates every Massif Maps brand asset from the ONE mark geometry below: the website logo and
// favicon, the social card, the GitHub avatar, and the launcher icons of both demo apps.
//
//   npm i @resvg/resvg-js && node scripts/gen-branding.mjs
//
// See docs/maintenance/branding.md for what lands where and what still has to be uploaded by hand.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

// ---------------------------------------------------------------------------------------------
// The mark. Two peaks on a 512 grid, base at y=402, lit face + shaded face each, contour lines at
// elevations SHARED by both peaks - that is what makes it read as terrain rather than as bunting.
// ---------------------------------------------------------------------------------------------

const BASE = 402

const FACES = [
  { id: 'TealLit',   d: 'M159 231 L56 402 L170 402 Z',  from: 231, stops: ['#12E3CF', '#00AB9C'] },
  { id: 'TealShade', d: 'M159 231 L170 402 L256 402 Z', from: 231, stops: ['#00A093', '#00736A'] },
  { id: 'BlueLit',   d: 'M296 128 L147 402 L308 402 Z', from: 128, stops: ['#4FA3F7', '#1C74D4'] },
  { id: 'BlueShade', d: 'M296 128 L308 402 L456 402 Z', from: 128, stops: ['#0C58B6', '#063877'] },
]

// A contour sags towards the viewer at the ridge, so each peak bows about its own summit x.
const contour = (cx, halfWidth, y) => `M${cx - halfWidth} ${y} Q${cx} ${y + 20} ${cx + halfWidth} ${y}`

const CONTOURS = [
  { clip: 'M159 231 L56 402 L256 402 Z',  cx: 159, half: 200, ys: [272, 304, 336, 368] },
  { clip: 'M296 128 L147 402 L456 402 Z', cx: 296, half: 240, ys: [176, 208, 240, 272, 304, 336, 368] },
]

const CONTOUR_STROKE = { color: '#ffffff', opacity: 0.22, width: 3.5 }

// Union silhouette, for the Android themed (monochrome) icon.
const SILHOUETTE = 'M296 128 L147 402 L456 402 Z M159 231 L56 402 L256 402 Z'

// The icon tile is white: the peaks are saturated enough to carry themselves, and they read
// brighter on it than on the night sky the card still uses.
const TILE_TOP = '#FFFFFF'
const TILE_BOTTOM = '#EAF1F7'
const GLOW = '#1FA9C9'
const GLOW_OPACITY = 0.20

// The mark inside a 1024 icon tile: 70% of the width, optically centred (a mountain is
// bottom-heavy, so its box sits slightly below centre). The glow sits on its baseline.
const TILE = { size: 1024, scale: 1.8, tx: 51.2, ty: 45 }
const glowCy = t => ((BASE * t.scale + t.ty) / t.size).toFixed(3)

// ---------------------------------------------------------------------------------------------
// SVG emitters
// ---------------------------------------------------------------------------------------------

const GENERATED = '<!-- Generated by scripts/gen-branding.mjs - do not edit. -->'

const markDefs = () => [
  ...FACES.map(f =>
    `    <linearGradient id="mm${f.id}" x1="0" y1="${f.from}" x2="0" y2="${BASE}" gradientUnits="userSpaceOnUse">\n` +
    `      <stop offset="0" stop-color="${f.stops[0]}"/><stop offset="1" stop-color="${f.stops[1]}"/>\n` +
    `    </linearGradient>`),
  ...CONTOURS.map((c, i) => `    <clipPath id="mmClip${i}"><path d="${c.clip}"/></clipPath>`),
].join('\n')

// The faces of one peak, then its contours, then the next peak on top of them.
const markBody = (indent = '  ') => {
  const out = []
  CONTOURS.forEach((c, i) => {
    for (const f of FACES.slice(i * 2, i * 2 + 2)) out.push(`${indent}<path d="${f.d}" fill="url(#mm${f.id})"/>`)
    out.push(`${indent}<g clip-path="url(#mmClip${i})" fill="none" stroke="${CONTOUR_STROKE.color}" ` +
      `stroke-opacity="${CONTOUR_STROKE.opacity}" stroke-width="${CONTOUR_STROKE.width}">`)
    for (const y of c.ys) out.push(`${indent}  <path d="${contour(c.cx, c.half, y)}"/>`)
    out.push(`${indent}</g>`)
  })
  return out.join('\n')
}

const markSvg = () =>
`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" role="img" aria-label="Massif Maps">
  <title>Massif Maps</title>
  ${GENERATED}
  <defs>
${markDefs()}
  </defs>
${markBody()}
</svg>
`

// The navbar logo: the mark alone, cropped to its own bounding box with a little air.
const logoSvg = () =>
`<svg xmlns="http://www.w3.org/2000/svg" viewBox="46 112 420 306" width="44" height="32" role="img" aria-label="Massif Maps">
  <title>Massif Maps</title>
  ${GENERATED}
  <defs>
${markDefs()}
  </defs>
${markBody()}
</svg>
`

// shape: 'square' (full bleed, what iOS and the avatar want) | 'rounded' | 'circle'.
const iconSvg = ({ size = 1024, shape = 'square', tile = TILE } = {}) => {
  const S = tile.size
  const clip = shape === 'circle'
    ? `<circle cx="${S / 2}" cy="${S / 2}" r="${S / 2}"/>`
    : `<rect width="${S}" height="${S}" rx="${shape === 'rounded' ? Math.round(S * 0.22) : 0}"/>`
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S}" width="${size}" height="${size}" role="img" aria-label="Massif Maps">
  <title>Massif Maps</title>
  ${GENERATED}
  <defs>
${markDefs()}
    <linearGradient id="mmSky" x1="0" y1="0" x2="0" y2="${S}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="${TILE_TOP}"/><stop offset="1" stop-color="${TILE_BOTTOM}"/>
    </linearGradient>
    <radialGradient id="mmGlow" cx="0.5" cy="${glowCy(tile)}" r="0.55">
      <stop offset="0" stop-color="${GLOW}" stop-opacity="${GLOW_OPACITY}"/>
      <stop offset="1" stop-color="${GLOW}" stop-opacity="0"/>
    </radialGradient>
    <clipPath id="mmShape">${clip}</clipPath>
  </defs>
  <g clip-path="url(#mmShape)">
    <rect width="${S}" height="${S}" fill="url(#mmSky)"/>
    <rect width="${S}" height="${S}" fill="url(#mmGlow)"/>
    <g transform="translate(${tile.tx} ${tile.ty}) scale(${tile.scale})">
${markBody('      ')}
    </g>
  </g>
</svg>
`
}

// The favicon is the bare mark, no tile: cropped square around it so the peaks get the whole
// 16px rather than sharing it with a background.
const faviconSvg = () =>
`<svg xmlns="http://www.w3.org/2000/svg" viewBox="36 45 440 440" width="32" height="32" role="img" aria-label="Massif Maps">
  <title>Massif Maps</title>
  ${GENERATED}
  <defs>
${markDefs()}
  </defs>
${markBody()}
</svg>
`

// ---------------------------------------------------------------------------------------------
// Social card. Platform pills, not brand glyphs - the Android robot and the Apple logo are
// trademarks with usage terms we would have to follow.
// ---------------------------------------------------------------------------------------------

const FONT = 'system-ui,-apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif'

// The three the site's own website/src/data/platforms.js marks 'supported', then the dashed pill
// that has to keep working when a fourth arrives.
const PILLS = [
  { label: 'Android', dot: '#00C4B3', w: 168 },
  { label: 'iOS', dot: '#2C8BF0', w: 114 },
  { label: 'NativeScript', dot: '#C8763C', w: 226 },
  { label: '+ more', dot: null, w: 142 },
]

const pill = (p, x, y, h) => {
  const cx = x + p.w / 2
  const dot = p.dot ? `<circle cx="${x + 30}" cy="${y + h / 2}" r="7" fill="${p.dot}"/>` : ''
  const tx = p.dot ? cx + 12 : cx
  return `    <g>
      <rect x="${x}" y="${y}" width="${p.w}" height="${h}" rx="${h / 2}" fill="${p.dot ? '#16273F' : 'none'}" stroke="${p.dot ? '#26405F' : '#2B4463'}" stroke-width="2"${p.dot ? '' : ' stroke-dasharray="7 7"'}/>
      ${dot}
      <text x="${tx}" y="${y + h / 2 + 9}" text-anchor="middle" font-family="${FONT}" font-size="24" font-weight="600" fill="#C3D6EA">${p.label}</text>
    </g>`
}

const socialCardSvg = () => {
  const W = 1200, H = 630
  const pillY = 384, pillH = 52
  // The card's icon is the 1024 tile shrunk, not a second composition.
  const T = { x: 96, y: 191, size: 248 }
  const k = T.size / TILE.size
  const tile = { s: TILE.scale * k, x: T.x + TILE.tx * k, y: T.y + TILE.ty * k }
  let x = 392
  const pills = PILLS.map(p => { const s = pill(p, x, pillY, pillH); x += p.w + 14; return s }).join('\n')
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-label="Massif Maps - vector maps, 3D terrain, routing and geocoding on Android, iOS and more">
  <title>Massif Maps</title>
  ${GENERATED}
  <defs>
${markDefs()}
    <linearGradient id="mmSky" x1="0" y1="0" x2="0" y2="${H}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#0C1E36"/><stop offset="1" stop-color="#070F1C"/>
    </linearGradient>
    <radialGradient id="mmHalo" cx="0.22" cy="0.5" r="0.62">
      <stop offset="0" stop-color="${GLOW}" stop-opacity="0.20"/>
      <stop offset="1" stop-color="${GLOW}" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="mmTileSky" x1="0" y1="191" x2="0" y2="439" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="${TILE_TOP}"/><stop offset="1" stop-color="${TILE_BOTTOM}"/>
    </linearGradient>
    <radialGradient id="mmTileGlow" cx="0.5" cy="${glowCy(TILE)}" r="0.55">
      <stop offset="0" stop-color="${GLOW}" stop-opacity="${GLOW_OPACITY}"/>
      <stop offset="1" stop-color="${GLOW}" stop-opacity="0"/>
    </radialGradient>
    <clipPath id="mmTile"><rect x="${T.x}" y="${T.y}" width="${T.size}" height="${T.size}" rx="56"/></clipPath>
  </defs>

  <rect width="${W}" height="${H}" fill="url(#mmSky)"/>
  <rect width="${W}" height="${H}" fill="url(#mmHalo)"/>
  <path d="M0 ${H} L210 500 L400 566 L610 470 L820 548 L1010 452 L1200 520 L1200 ${H} Z" fill="#0E2138"/>
  <path d="M0 ${H} L260 566 L520 604 L780 552 L1030 598 L1200 566 L1200 ${H} Z" fill="#122B47"/>

  <g clip-path="url(#mmTile)">
    <rect x="${T.x}" y="${T.y}" width="${T.size}" height="${T.size}" fill="url(#mmTileSky)"/>
    <rect x="${T.x}" y="${T.y}" width="${T.size}" height="${T.size}" fill="url(#mmTileGlow)"/>
    <g transform="translate(${tile.x.toFixed(2)} ${tile.y.toFixed(2)}) scale(${tile.s.toFixed(4)})">
${markBody('      ')}
    </g>
  </g>

  <text x="392" y="300" font-family="${FONT}" font-size="86" font-weight="700" fill="#ffffff">Massif Maps</text>
  <text x="394" y="350" font-family="${FONT}" font-size="26" fill="#93AECB">Vector maps, 3D terrain, routing &amp; geocoding &#8212; one C++ core</text>
${pills}
</svg>
`
}

// ---------------------------------------------------------------------------------------------
// Android VectorDrawables. The adaptive icon is only read on API 26+, so the gradients (API 24+)
// are safe here; API 21-25 gets the rasterised mipmaps instead.
// ---------------------------------------------------------------------------------------------

// 108dp viewport, of which only the central 72dp (288px) survives a circular mask. The mark's
// widest points are its two base corners, so it is lifted until they sit inside that circle:
// base at y=258 puts them at r=131 of the 144 available.
const ADAPTIVE = { scale: 0.62, tx: 57.28, ty: 8.76 }
const ADAPTIVE_BASE_Y = BASE * ADAPTIVE.scale + ADAPTIVE.ty

const vdPath = d => d.replace(/ /g, ',').replace(/,([A-Za-z])/g, '$1').replace(/([A-Za-z]),/g, '$1')

const androidForeground = () => {
  const body = []
  CONTOURS.forEach((c, i) => {
    for (const f of FACES.slice(i * 2, i * 2 + 2)) {
      body.push(`      <path android:pathData="${vdPath(f.d)}">
        <aapt:attr name="android:fillColor">
          <gradient android:type="linear" android:startX="0" android:startY="${f.from}" android:endX="0" android:endY="${BASE}">
            <item android:offset="0" android:color="${f.stops[0]}"/>
            <item android:offset="1" android:color="${f.stops[1]}"/>
          </gradient>
        </aapt:attr>
      </path>`)
    }
    body.push('      <group>')
    body.push(`        <clip-path android:pathData="${vdPath(c.clip)}"/>`)
    for (const y of c.ys) {
      body.push(`        <path android:pathData="${vdPath(contour(c.cx, c.half, y))}" android:fillColor="#00000000" ` +
        `android:strokeColor="${CONTOUR_STROKE.color}" android:strokeAlpha="${CONTOUR_STROKE.opacity}" ` +
        `android:strokeWidth="${CONTOUR_STROKE.width}"/>`)
    }
    body.push('      </group>')
  })
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen-branding.mjs - do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="432"
    android:viewportHeight="432">
    <group android:translateX="${ADAPTIVE.tx}" android:translateY="${ADAPTIVE.ty}" android:scaleX="${ADAPTIVE.scale}" android:scaleY="${ADAPTIVE.scale}">
${body.join('\n')}
    </group>
</vector>
`
}

const androidBackground = () => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen-branding.mjs - do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="432"
    android:viewportHeight="432">
    <path android:pathData="M0,0h432v432h-432z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="0" android:endY="432">
                <item android:offset="0" android:color="${TILE_TOP}"/>
                <item android:offset="1" android:color="${TILE_BOTTOM}"/>
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="M0,0h432v432h-432z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="216" android:centerY="${ADAPTIVE_BASE_Y.toFixed(1)}" android:gradientRadius="238">
                <item android:offset="0" android:color="#61${GLOW.slice(1)}"/>
                <item android:offset="1" android:color="#00${GLOW.slice(1)}"/>
            </gradient>
        </aapt:attr>
    </path>
</vector>
`

// Android 13 themed icons tint a single-colour silhouette, so it carries no faces and no contours.
const androidMonochrome = () => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen-branding.mjs - do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="432"
    android:viewportHeight="432">
    <group android:translateX="${ADAPTIVE.tx}" android:translateY="${ADAPTIVE.ty}" android:scaleX="${ADAPTIVE.scale}" android:scaleY="${ADAPTIVE.scale}">
        <path android:pathData="${vdPath(SILHOUETTE)}" android:fillColor="#FFFFFF"/>
    </group>
</vector>
`

const adaptiveIcon = () => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen-branding.mjs - do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`

// ---------------------------------------------------------------------------------------------
// Emit
// ---------------------------------------------------------------------------------------------

const write = (rel, content) => {
  const p = path.join(ROOT, rel)
  fs.mkdirSync(path.dirname(p), { recursive: true })
  fs.writeFileSync(p, content)
  console.log('  ' + rel)
}

let Resvg
try {
  ({ Resvg } = await import('@resvg/resvg-js'))
} catch {
  console.error('@resvg/resvg-js is missing - the SVGs will be written, the PNGs skipped.')
  console.error('  npm i @resvg/resvg-js')
}

const png = (rel, svg, width) => {
  if (!Resvg) return
  const buf = new Resvg(svg, { fitTo: { mode: 'width', value: width } }).render().asPng()
  const p = path.join(ROOT, rel)
  fs.mkdirSync(path.dirname(p), { recursive: true })
  fs.writeFileSync(p, buf)
  console.log('  ' + rel + `  (${width}px)`)
}

console.log('branding:')

// Masters + website
write('media/branding/mark.svg', markSvg())
write('media/branding/icon.svg', iconSvg())
write('website/static/img/logo.svg', logoSvg())
write('website/static/img/favicon.svg', faviconSvg())
write('website/static/img/social-card.svg', socialCardSvg())

// The GitHub org/repo avatar, uploaded by hand in the repo settings.
png('media/branding/github-avatar.png', iconSvg(), 1024)

// og:image. Twitter, Slack and LinkedIn do not rasterise SVG, so the card ships as a PNG too.
if (Resvg) {
  const card = new Resvg(socialCardSvg(), { fitTo: { mode: 'width', value: 1200 } }).render().asPng()
  fs.writeFileSync(path.join(ROOT, 'website/static/img/social-card.png'), card)
  console.log('  website/static/img/social-card.png  (1200x630)')
}

// Android demo
const ANDROID = 'scripts/android-dev/app/src/main/res'
write(`${ANDROID}/drawable/ic_launcher_foreground.xml`, androidForeground())
write(`${ANDROID}/drawable/ic_launcher_background.xml`, androidBackground())
write(`${ANDROID}/drawable/ic_launcher_monochrome.xml`, androidMonochrome())
write(`${ANDROID}/mipmap-anydpi-v26/ic_launcher.xml`, adaptiveIcon())
write(`${ANDROID}/mipmap-anydpi-v26/ic_launcher_round.xml`, adaptiveIcon())
for (const [dpi, size] of [['mdpi', 48], ['hdpi', 72], ['xhdpi', 96], ['xxhdpi', 144], ['xxxhdpi', 192]]) {
  png(`${ANDROID}/mipmap-${dpi}/ic_launcher.png`, iconSvg({ shape: 'rounded' }), size)
  png(`${ANDROID}/mipmap-${dpi}/ic_launcher_round.png`, iconSvg({ shape: 'circle' }), size)
}

// iOS demo
const APPICON = 'scripts/ios-dev/MassifDemo/Resources/Assets.xcassets/AppIcon.appiconset'
write('scripts/ios-dev/MassifDemo/Resources/Assets.xcassets/Contents.json',
  JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2) + '\n')
write(`${APPICON}/Contents.json`, JSON.stringify({
  images: [{ filename: 'AppIcon-1024.png', idiom: 'universal', platform: 'ios', size: '1024x1024' }],
  info: { author: 'xcode', version: 1 },
}, null, 2) + '\n')
png(`${APPICON}/AppIcon-1024.png`, iconSvg(), 1024)
