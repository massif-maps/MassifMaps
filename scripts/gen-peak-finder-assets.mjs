#!/usr/bin/env node
/*
 * Writes the peak finder's generated text - both shaders and the summit names' CartoCSS - for the
 * native ports, from the web example's own modules (web/examples/peak-finder/look.mjs):
 *
 *   scripts/android-dev/app/src/main/assets/peak-finder/   read by Android, bundled by iOS project.yml
 *   integrations/nativescript/demo-snippets/svelte/examples/peak-finder/look.ts   when checked out
 *
 * The CartoCSS ranks names by the eye's altitude and hangs them from a row sized to the view, so it
 * names `@eye_elevation` and `@label_band`, and each port prepends both when it builds the style
 * (the row's formula is `labelBand` in look.mjs).
 *
 *   node scripts/gen-peak-finder-assets.mjs
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { INK_SHADER, LABEL, SURFACE_SHADER, summitsStyle } from '../web/examples/peak-finder/look.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EYE = 987654;
const BAND = 0.987654;
// Roboto where the platform has it, Helvetica Neue on iOS: a face list stops at the first match.
const css = summitsStyle({ ...LABEL, band: BAND }, EYE, { regular: 'Roboto, Helvetica Neue', bold: 'Roboto-Bold, HelveticaNeue-Bold' });
if (!css.includes(`- ${EYE})`) || !css.includes(`text-callout-screen-anchor: ${BAND};`)) {
  throw new Error('peaksStyle no longer takes the eye elevation or the row height as written here - update this generator');
}
const summits = css.replace(`- ${EYE})`, '- @eye_elevation)').replace(`text-callout-screen-anchor: ${BAND};`, 'text-callout-screen-anchor: @label_band;');

const assets = path.join(root, 'scripts/android-dev/app/src/main/assets/peak-finder');
mkdirSync(assets, { recursive: true });
writeFileSync(path.join(assets, 'relief-surface.glsl'), SURFACE_SHADER);
writeFileSync(path.join(assets, 'relief-ink.glsl'), INK_SHADER);
writeFileSync(path.join(assets, 'summits.mss'), summits + '\n');
console.log(`assets     ${path.relative(root, assets)}`);

const nativescript = path.join(root, 'integrations/nativescript/demo-snippets/svelte/examples');
if (existsSync(nativescript)) {
  mkdirSync(path.join(nativescript, 'peak-finder'), { recursive: true });
  const file = path.join(nativescript, 'peak-finder', 'look.ts');
  writeFileSync(file, '// GENERATED by scripts/gen-peak-finder-assets.mjs in the SDK repo - do not edit.\n' +
    `export const SURFACE_SHADER = ${JSON.stringify(SURFACE_SHADER)};\n` +
    `export const INK_SHADER = ${JSON.stringify(INK_SHADER)};\n` +
    `export const SUMMITS_CSS = ${JSON.stringify(summits + '\n')};\n`);
  console.log(`nativescript ${path.relative(root, file)}`);
} else {
  console.log('nativescript not checked out - its look.ts is unchanged');
}
